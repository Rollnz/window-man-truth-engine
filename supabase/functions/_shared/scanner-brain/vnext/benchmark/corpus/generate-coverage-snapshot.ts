// Sprint 07B.3 — Regenerates the corpus coverage snapshot.
//
//   deno run --allow-read --allow-write \
//     supabase/functions/_shared/scanner-brain/vnext/benchmark/corpus/generate-coverage-snapshot.ts
//
// Writes:
//   - corpus/CORPUS_COVERAGE.json      (canonical snapshot)
//   - src/data/corpusCoverage.ts       (typed mirror consumed by the dashboard)
import { buildCoverageReport, REQUIRED_ARCHETYPES } from "./coverage-report.ts";
import { CORPUS_V1_PRE_INVENTORY } from "./inventory.ts";

const report = {
  generated_from: "CORPUS_V1_PRE_INVENTORY",
  required_archetypes: REQUIRED_ARCHETYPES,
  ...buildCoverageReport(CORPUS_V1_PRE_INVENTORY),
};

const json = JSON.stringify(report, null, 2) + "\n";
const here = new URL(".", import.meta.url).pathname;
await Deno.writeTextFile(`${here}CORPUS_COVERAGE.json`, json);

const mirror = `// AUTO-GENERATED by supabase/functions/_shared/scanner-brain/vnext/benchmark/corpus/generate-coverage-snapshot.ts
// Do not edit by hand. Read-only benchmark snapshot — contains no PII.
export const CORPUS_COVERAGE = ${json.trimEnd()} as const;

export type CorpusCoverageSnapshot = typeof CORPUS_COVERAGE;
`;
await Deno.writeTextFile(
  new URL("../../../../../../../../src/data/corpusCoverage.ts", import.meta.url).pathname,
  mirror,
);

console.log("coverage snapshot written");
